//! The CLI contract of AGENTS.md: JSON with a schema, exit codes 0, 1 and 2.

use std::path::PathBuf;
use std::process::{Command, Output};

fn run(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_sqlautopsy"))
        .args(args)
        .output()
        .expect("run sqlautopsy")
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("sqlautopsy-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// Synthetic dump text, written as SQL Server writes it: UTF-16 LE with a BOM, CRLF.
fn write_utf16(path: &PathBuf, text: &str) {
    let mut bytes = vec![0xFF, 0xFE];
    let crlf = text.replace('\n', "\r\n");
    bytes.extend(crlf.encode_utf16().flat_map(u16::to_le_bytes));
    std::fs::write(path, bytes).unwrap();
}

#[test]
fn json_report_for_a_folder() {
    let dir = scratch("json");
    write_utf16(
        &dir.join("SQLDump0001.txt"),
        "This file is generated by Microsoft SQL Server\nversion 16.0.4135.4\n\
         * BEGIN STACK DUMP:\n*   03/04/25 10:11:12 spid 55\n*\n* Latch timeout\n*\n* ****\n",
    );
    std::fs::write(dir.join("SQLDump0001.mdmp"), b"MDMP").unwrap();
    std::fs::write(dir.join("ERRORLOG"), b"not a dump").unwrap();

    let out = run(&["--format", "json", dir.to_str().unwrap()]);
    assert_eq!(
        out.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let report: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
    assert_eq!(report["schema"], 1);
    let dump = &report["dumps"][0];
    assert_eq!(dump["name"], "SQLDump0001");
    assert_eq!(dump["files"].as_array().unwrap().len(), 2);
    assert_eq!(dump["text"]["product"], "SQL Server 2022");
    assert_eq!(dump["text"]["condition"], "Latch timeout");
    assert_eq!(dump["text"]["time"], "2025-03-04T10:11:12");
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn exit_codes() {
    assert_eq!(run(&[]).status.code(), Some(2));
    assert_eq!(run(&["--format", "xml", "."]).status.code(), Some(2));
    assert_eq!(run(&["--bogus"]).status.code(), Some(2));
    assert_eq!(run(&["/no/such/folder"]).status.code(), Some(1));
    let empty = scratch("empty");
    assert_eq!(run(&[empty.to_str().unwrap()]).status.code(), Some(1));
    // Only an .mdmp: listed, but nothing could be read yet.
    std::fs::write(empty.join("SQLDump0002.mdmp"), b"MDMP").unwrap();
    assert_eq!(run(&[empty.to_str().unwrap()]).status.code(), Some(1));
    let _ = std::fs::remove_dir_all(&empty);
}

#[test]
fn stack_reads_standard_input() {
    use std::io::Write as _;
    use std::process::Stdio;

    let histogram = r#"<HistogramTarget><Slot count="4"><value><![CDATA[<frame id="00" pdb="sqllang.pdb" age="2" guid="A1EE9134-BEFA-47A3-B2A6-1129DC226721" module="sqllang" rva="0x31C857" /><frame id="01" module="SqlDK" rva="0x8D8E" />]]></value></Slot></HistogramTarget>"#;
    let run_stdin = |input: &str| {
        let mut child = Command::new(env!("CARGO_BIN_EXE_sqlautopsy"))
            .args(["--no-symbols", "--format", "json", "stack"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        child
            .stdin
            .take()
            .unwrap()
            .write_all(input.as_bytes())
            .unwrap();
        child.wait_with_output().unwrap()
    };
    let out = run_stdin(histogram);
    assert_eq!(out.status.code(), Some(0));
    let report: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
    assert_eq!(report["schema"], 1);
    assert_eq!(report["stacks"][0]["count"], 4);
    assert_eq!(report["stacks"][0]["frames"][1]["module"], "SqlDK");
    assert_eq!(run_stdin("no frames here").status.code(), Some(1));
    assert_eq!(run(&["stack", "a", "b"]).status.code(), Some(2));
}
